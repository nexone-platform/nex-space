#!/usr/bin/env node
// What the map editor is allowed to offer, read off the disk.
//
// The editor needs a list of every prop that exists. Typing 200 filenames into
// a TypeScript file by hand is a list that is wrong within a week, and globbing
// at runtime is not possible: these live in public/, which Vite copies rather
// than compiles, so nothing in the bundle knows they are there.
//
// So the list is generated and committed, and preflight runs this with --check
// to fail the build when the folder and the file disagree — an editor offering
// a prop that 404s is worse than one that never offered it.
//
//   node scripts/asset-catalogue.mjs          # rewrite the catalogue
//   node scripts/asset-catalogue.mjs --check  # fail if it is out of date
import { readdirSync, readFileSync, writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ASSETS = join(ROOT, "apps/web/public/assets");
const OUT = join(ROOT, "apps/web/src/editor/catalogue.ts");

// folder -> how the scene names a prop from it. "furniture" is the fallback
// folder, so its keys are bare; everything else carries its folder.
const FOLDERS = [
  { dir: "furniture", prefix: "", label: "เฟอร์นิเจอร์" },
  { dir: "office", prefix: "office/", label: "ออฟฟิศ" },
  { dir: "decor", prefix: "", label: "ของแขวนผนัง" },
  { dir: "outdoor", prefix: "", label: "กลางแจ้ง" },
];

/**
 * Chairs ship as eight directions of the same chair, and a palette listing all
 * eight is 128 entries for 16 chairs. Only the south-facing one is offered.
 *
 * The other seven are still on disk and still used: a map may place a chair
 * facing any of them by naming the key directly, and sitting down faces you the
 * way the seat does. What the editor offers is one entry per chair, not one
 * direction per chair.
 */
const CHAIR_DIR = /^(chair-\d+)-(east|north|north-east|north-west|south|south-east|south-west|west)$/;

function scan() {
  const out = [];
  for (const { dir, prefix, label } of FOLDERS) {
    const files = readdirSync(join(ASSETS, dir))
      .filter((f) => f.endsWith(".png"))
      .map((f) => f.slice(0, -4))
      .filter((name) => {
        const m = CHAIR_DIR.exec(name);
        return !m || m[2] === "south";
      })
      .sort();
    out.push({ dir, label, keys: files.map((f) => prefix + f) });
  }
  return out;
}

const groups = scan();
const total = groups.reduce((n, g) => n + g.keys.length, 0);

const body = `// GENERATED by scripts/asset-catalogue.mjs — do not edit by hand.
//
// Every prop the map editor may place, read off apps/web/public/assets. Those
// files live in public/, which Vite copies rather than compiles, so nothing in
// the bundle would otherwise know they exist.
//
// Chairs are listed once each, facing south: the game rotates a placed chair,
// and offering all eight directions would be ${"128"} palette entries for 16 chairs.
//
// Regenerate with:  node scripts/asset-catalogue.mjs

export interface PropGroup {
  /** the folder on disk, and the fallback folder for its bare keys */
  dir: string;
  label: string;
  keys: string[];
}

/** ${total} props across ${groups.length} groups */
export const CATALOGUE: PropGroup[] = ${JSON.stringify(groups, null, 2)};

/** every key in one flat list, for lookups */
export const ALL_PROPS: string[] = CATALOGUE.flatMap((g) => g.keys);
`;

const check = process.argv.includes("--check");
let existing = "";
try { existing = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n"); } catch { /* first run */ }

if (check) {
  if (existing === body) {
    console.log(`catalogue: ${total} props, up to date`);
    process.exit(0);
  }
  console.error("catalogue: apps/web/src/editor/catalogue.ts is out of date");
  console.error(`  the assets folder now holds ${total} placeable props`);
  console.error("  regenerate with:  node scripts/asset-catalogue.mjs");
  process.exit(1);
}

writeFileSync(OUT, body);
console.log(`catalogue: wrote ${total} props to apps/web/src/editor/catalogue.ts`);
for (const g of groups) console.log(`  ${g.dir.padEnd(10)} ${g.keys.length}`);
